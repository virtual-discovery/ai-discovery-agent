"""Refetch the pinned Ge and Te pseudopotentials for fresh-gete-ferroelectric-well and vendor them into the lab.

    python3 -B benchmarks/construction/fresh-gete-ferroelectric-well/fetch_pseudos.py [--install]

1. The SSSP 1.3.0 PBE precision choices for Ge and Te,
   ge_pbe_v1.4.uspp.F.UPF (GBRV 1.4 ultrasoft, 3d in valence; license GPL v3) and
   Te.us.z_6.ld1.psl.v1.0.0-low.upf (PSlibrary 1.0.0 ultrasoft, regenerated by the SSSP authors; GPL v2 or later),
   from the SSSP library, Materials Cloud Archive record rcyfm-68h65 (DOI 10.24435/materialscloud:f3-ym;
   Prandini et al., npj Comput. Mater. 4, 72 (2018)). The archive files are checked against the MD5s published by
   the record API, each UPF against the MD5 in the SSSP metadata and the SHA256 pinned in pseudo_checksums.json.
   The record is CC BY 4.0 except the pseudopotentials, which keep their family licenses (LICENSE.txt).
2. The PSlibrary 1.0.0 pair used for the spin-orbit comparison (A. Dal Corso, Comput. Mater. Sci. 95, 337 (2014)),
   from the Quantum ESPRESSO pseudopotential library https://pseudopotentials.quantum-espresso.org/upf_files/:
   Ge.pbe-n-rrkjus_psl.1.0.0.UPF / Ge.rel-pbe-n-rrkjus_psl.1.0.0.UPF and
   Te.pbe-n-rrkjus_psl.1.0.0.UPF / Te.rel-pbe-n-rrkjus_psl.1.0.0.UPF (scalar-relativistic / fully relativistic,
   generated with the same parameters); license GNU GPL v2 or later. Checked against the pinned MD5 and SHA256.

Downloads go to ~/.cache/ai-theorist/fresh-gete-ferroelectric-well/ (about 63 MB, deletable afterwards).
--install copies the UPF files and the SSSP LICENSE.txt (as SSSP_LICENSE.txt) into environment/lab/ (lab image
only; the agent image never sees them).
"""
import hashlib
import json
import shutil
import sys
import tarfile
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
RECORD = 'https://archive.materialscloud.org/api/records/rcyfm-68h65'
ARCHIVE = ['SSSP_1.3.0_PBE_precision.tar.gz', 'SSSP_1.3.0_PBE_precision.json', 'LICENSE.txt']
PSL_URL = 'https://pseudopotentials.quantum-espresso.org/upf_files/'
SSSP_FILES = {'Ge': 'ge_pbe_v1.4.uspp.F.UPF', 'Te': 'Te.us.z_6.ld1.psl.v1.0.0-low.upf'}
PSL_FILES = ['Ge.pbe-n-rrkjus_psl.1.0.0.UPF', 'Ge.rel-pbe-n-rrkjus_psl.1.0.0.UPF',
             'Te.pbe-n-rrkjus_psl.1.0.0.UPF', 'Te.rel-pbe-n-rrkjus_psl.1.0.0.UPF']
CACHE = Path.home()/'.cache/ai-theorist/fresh-gete-ferroelectric-well'
LAB = HERE.parents[1]/'tasks/fresh-gete-ferroelectric-well/environment/lab'
PINNED = HERE/'pseudo_checksums.json'


def digest(path, algo):
    h = hashlib.new(algo)
    with open(path, 'rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def download(url, target):
    print('downloading', url, flush=True)
    with urllib.request.urlopen(url, timeout=600) as r, open(target, 'wb') as out:
        shutil.copyfileobj(r, out)


def main():
    pinned = json.loads(PINNED.read_text()) if PINNED.exists() else None
    CACHE.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(RECORD, timeout=60) as r:
        entries = json.load(r)['files']['entries']
    for name in ARCHIVE:
        md5 = entries[name]['checksum'].split(':', 1)[1]
        if pinned:
            assert md5 == pinned['archive_md5'][name], f'record MD5 of {name} changed: {md5}'
        target = CACHE/name
        if not target.exists() or digest(target, 'md5') != md5:
            download(f'{RECORD}/files/{name}/content', target)
        assert digest(target, 'md5') == md5, f'MD5 mismatch for {name}'
        print(name, target.stat().st_size, 'md5', md5)
    meta = json.loads((CACHE/'SSSP_1.3.0_PBE_precision.json').read_text())
    with tarfile.open(CACHE/'SSSP_1.3.0_PBE_precision.tar.gz') as tar:
        for element, name in SSSP_FILES.items():
            assert meta[element]['filename'] == name, meta[element]
            member = next(m for m in tar.getmembers() if Path(m.name).name == name)
            with tar.extractfile(member) as src, open(CACHE/name, 'wb') as dst:
                shutil.copyfileobj(src, dst)
            assert digest(CACHE/name, 'md5') == meta[element]['md5'], f'SSSP metadata MD5 mismatch for {name}'
            print('SSSP', element, meta[element])
    for name in PSL_FILES:
        if not (CACHE/name).exists() or (pinned and digest(CACHE/name, 'sha256') != pinned['upf'][name]['sha256']):
            download(PSL_URL + name, CACHE/name)
    record = {'archive_md5': {n: entries[n]['checksum'].split(':', 1)[1] for n in ARCHIVE}, 'upf': {}}
    for name in [*SSSP_FILES.values(), *PSL_FILES]:
        record['upf'][name] = {'md5': digest(CACHE/name, 'md5'), 'sha256': digest(CACHE/name, 'sha256'),
                               'bytes': (CACHE/name).stat().st_size}
        if pinned:
            assert record['upf'][name] == pinned['upf'][name], f'checksum mismatch for {name}'
        print(name, record['upf'][name])
    if not pinned:
        PINNED.write_text(json.dumps(record, indent=1) + '\n')
        print('pinned checksums written to', PINNED)
    if '--install' in sys.argv:
        for name in [*SSSP_FILES.values(), *PSL_FILES]:
            shutil.copy2(CACHE/name, LAB/name)
        shutil.copy2(CACHE/'LICENSE.txt', LAB/'SSSP_LICENSE.txt')
        print('installed into', LAB)


if __name__ == '__main__':
    main()

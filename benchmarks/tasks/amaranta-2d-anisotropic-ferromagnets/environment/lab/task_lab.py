"""Lab logic for amaranta-2d-anisotropic-ferromagnets.

`energies` requests return total energies of classical unit-vector spin configurations in a
diagonal n1 x n2 supercell of a compound's catalog cell. They are generated by the AMaRaNTA spin
model with the authors' archived parameters (private/model.json, written by
benchmarks/construction/amaranta-2d-anisotropic-ferromagnets/make_task.py) plus deterministic
noise of DFT-like size. Nothing graded is served: the targets (ground states, anisotropy energies,
the CrI3 bond exchange and ordering temperature, the CrSBr DM vector and gap, the energies of the
to_predict configurations) live in private/hidden.json.
"""
import hashlib
import json
import math
from pathlib import Path
import numpy as np

HERE = Path(__file__).parent
MODEL = json.loads((HERE/'private/model.json').read_text())
PRIVATE = json.loads((HERE/'private/hidden.json').read_text())
MAX_SITES, MAX_CONFIGS, SITES_PER_UNIT = 36, 6, 12
TYPES = ('ferromagnet', 'neel antiferromagnet', 'zigzag antiferromagnet', 'stripe antiferromagnet', 'noncollinear')


def _cost(n_sites, n_configs):
    return n_configs * int(math.ceil(n_sites / SITES_PER_UNIT))


def validate(request):
    if request.get('kind') != 'energies' or set(request) != {'kind', 'compound', 'supercell', 'spins'}:
        raise ValueError('Use {"kind": "energies", "compound": <name>, "supercell": [n1, n2], "spins": [configuration, ...]}')
    if request['compound'] not in MODEL:
        raise ValueError('compound must be one of %s' % sorted(MODEL))
    sc = request['supercell']
    if not (isinstance(sc, list) and len(sc) == 2 and all(type(n) is int and n >= 1 for n in sc)):
        raise ValueError('supercell must be [n1, n2] with positive integers (diagonal supercell of the catalog cell)')
    n_sites = len(MODEL[request['compound']]['basis']) * sc[0] * sc[1]
    if n_sites > MAX_SITES:
        raise ValueError('at most %d magnetic sites per supercell (requested %d)' % (MAX_SITES, n_sites))
    confs = request['spins']
    if not (isinstance(confs, list) and 1 <= len(confs) <= MAX_CONFIGS):
        raise ValueError('spins must be a list of 1-%d configurations' % MAX_CONFIGS)
    for conf in confs:
        if not (isinstance(conf, list) and len(conf) == n_sites):
            raise ValueError('each configuration needs one [sx, sy, sz] per magnetic site (%d sites)' % n_sites)
        for s in conf:
            if not (isinstance(s, list) and len(s) == 3 and all(isinstance(x, (int, float)) and not isinstance(x, bool)
                                                                  and math.isfinite(x) for x in s)):
                raise ValueError('spins must be finite [sx, sy, sz] triples')
            if math.sqrt(sum(x * x for x in s)) < 1e-6:
                raise ValueError('spin vectors must be nonzero (they are normalised to unit length)')
    return _cost(n_sites, len(confs))


def model_energy_meV(compound, n1, n2, spins):
    m = MODEL[compound]
    nb = len(m['basis'])
    e = np.asarray(spins, float)
    e = e / np.linalg.norm(e, axis=1, keepdims=True)
    S = e.reshape(nb, n1, n2, 3)
    E = 0.0
    for k0, k, m1, m2, J in m['bonds']:
        Sj = np.roll(np.roll(S[k], -m1, axis=0), -m2, axis=1)
        E += 0.5 * np.einsum('ija,ab,ijb->', S[k0], np.asarray(J, float), Sj)
    return float(E + m['K'] * np.sum(e[:, 2] ** 2))


def noise_meV(compound, n1, n2, spins):
    e = np.asarray(spins, float)
    e = e / np.linalg.norm(e, axis=1, keepdims=True)
    key = json.dumps([compound, n1, n2, np.round(e, 6).tolist()]).encode()
    seed = int(hashlib.sha256(key).hexdigest()[:16], 16)
    return float(np.random.default_rng(seed).normal() * MODEL[compound]['noise_meV'])


def run(request, workdir):
    c, (n1, n2) = request['compound'], request['supercell']
    m = MODEL[c]
    nb = len(m['basis'])
    cell, basis = np.array(m['cell']), np.array(m['basis'])
    pos = [basis[k] + i * cell[0] + j * cell[1] for k in range(nb) for i in range(n1) for j in range(n2)]
    energies = []
    for conf in request['spins']:
        E = len(pos) * m['e0_eV'] + (model_energy_meV(c, n1, n2, conf) + noise_meV(c, n1, n2, conf)) / 1000.0
        energies.append(round(E, 8))
    return {'compound': c, 'supercell': [n1, n2], 'n_sites': len(pos),
            'site_positions_A': [[round(float(x), 4) for x in p[:2]] for p in pos],
            'total_energies_eV': energies,
            'source': 'AMaRaNTA surrogate with the authors\' archived parameters plus DFT-like noise (no new DFT)'}


def finite(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def _vec(x, n):
    return isinstance(x, list) and len(x) == n and all(finite(v) for v in x)


def grade(payload, trace, validation):
    t = PRIVATE['thresholds']
    fields = ['ground_states', 'easy_axis_polar_deg', 'anisotropy_meV_per_Cr', 'CrI3_bond_exchange_meV', 'CrI3_Tc_K',
              'CrSBr_dm_vector_meV', 'CrSBr_spin_wave_gap_meV', 'energy_predictions_meV_per_site', 'evidence_ids']
    missing = [f for f in fields if f not in payload]
    if missing:
        return False, {'missing_fields': missing}
    names = sorted(PRIVATE['ground_states'])
    gs, pol, an = payload['ground_states'], payload['easy_axis_polar_deg'], payload['anisotropy_meV_per_Cr']
    if not (isinstance(gs, dict) and set(gs) == set(names) and all(isinstance(v, str) for v in gs.values())):
        return False, {'error': 'ground_states must give a type (string) for each compound: %s' % names}
    if not (isinstance(pol, dict) and set(pol) == set(names) and all(finite(v) for v in pol.values())):
        return False, {'error': 'easy_axis_polar_deg must give a finite angle for each compound'}
    if not (isinstance(an, dict) and set(an) == set(names) and all(isinstance(v, dict) and finite(v.get('total')) and
                                                                   finite(v.get('single_ion')) for v in an.values())):
        return False, {'error': 'anisotropy_meV_per_Cr must give {"total": x, "single_ion": y} for each compound'}
    bond = payload['CrI3_bond_exchange_meV']
    if not (isinstance(bond, dict) and all(finite(bond.get(k)) for k in ('J', 'K', 'Gamma', 'Gamma_prime'))):
        return False, {'error': 'CrI3_bond_exchange_meV must give finite J, K, Gamma, Gamma_prime'}
    if not (finite(payload['CrI3_Tc_K']) and finite(payload['CrSBr_spin_wave_gap_meV']) and _vec(payload['CrSBr_dm_vector_meV'], 3)):
        return False, {'error': 'CrI3_Tc_K and CrSBr_spin_wave_gap_meV must be finite numbers, CrSBr_dm_vector_meV a list of 3'}
    pred, ptargets = payload['energy_predictions_meV_per_site'], PRIVATE['predictions']
    if not isinstance(pred, dict) or set(pred) != set(ptargets) or not all(finite(x) for x in pred.values()):
        return False, {'error': 'energy_predictions_meV_per_site must give a finite value for every to_predict id'}
    executed = {r['id'] for r in trace if r['status'] == 'complete'}
    ids = payload['evidence_ids']
    checks = {'evidence_executed': isinstance(ids, list) and len(ids) > 0 and all(type(i) is int for i in ids) and set(ids) <= executed}
    report = {}
    tol = lambda ref: max(t['anisotropy_abs_meV'], t['anisotropy_rel'] * abs(ref))
    for n in names:
        checks['type:' + n] = gs[n].strip().lower().replace('é', 'e') == PRIVATE['ground_states'][n].lower()
        ref = PRIVATE['easy_axis_polar_deg'][n]
        p = abs(float(pol[n])) % 180.0
        p = min(p, 180.0 - p)
        checks['easy_axis:' + n] = abs(p - ref) <= t['polar_tol_deg']
        for part in ('total', 'single_ion'):
            r = PRIVATE['anisotropy_meV_per_Cr'][n][part]
            err = an[n][part] - r
            checks[f'anisotropy_{part}:{n}'] = abs(err) <= tol(r)
            report[f'anisotropy_{part}_error_meV:{n}'] = err
    ref = PRIVATE['CrI3_bond_exchange_meV']
    checks['CrI3_bond_J'] = abs(bond['J'] - ref['J']) <= t['bond_J_abs_meV']
    checks['CrI3_bond_K'] = abs(bond['K'] - ref['K']) <= t['bond_K_rel'] * abs(ref['K'])
    checks['CrI3_bond_Gamma'] = abs(bond['Gamma'] - ref['Gamma']) <= t['bond_Gamma_abs_meV']
    report['CrI3_bond_errors_meV'] = {k: bond[k] - ref[k] for k in ('J', 'K', 'Gamma', 'Gamma_prime')}
    rel = payload['CrI3_Tc_K'] / PRIVATE['CrI3_Tc_K'] - 1
    checks['CrI3_Tc'] = abs(rel) <= t['Tc_rel']
    report['CrI3_Tc_relative_error'] = rel
    dD = float(np.linalg.norm(np.asarray(payload['CrSBr_dm_vector_meV'], float) - np.asarray(PRIVATE['CrSBr_dm_vector_meV'])))
    checks['CrSBr_dm_vector'] = dD <= t['dm_abs_meV']
    report['CrSBr_dm_error_meV'] = dD
    rel = payload['CrSBr_spin_wave_gap_meV'] / PRIVATE['CrSBr_spin_wave_gap_meV'] - 1
    checks['CrSBr_gap'] = abs(rel) <= t['gap_rel']
    report['CrSBr_gap_relative_error'] = rel
    by = {}
    for pid, v in ptargets.items():
        by.setdefault(pid.split('-')[0], []).append((pred[pid] - v) ** 2)
    for c, errs in by.items():
        rmse = math.sqrt(sum(errs) / len(errs))
        checks['predictions:' + c] = rmse <= t['prediction_rmse_meV_per_site']
        report['prediction_rmse_meV_per_site:' + c] = rmse
    return all(checks.values()), {'checks': checks, **report}
